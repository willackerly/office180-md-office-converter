/**
 * Build/check the deterministic browser IIFE from shared TypeScript sources.
 *
 * CONTRACT:C4-PPTV-SOURCE.1.1
 * CONTRACT:C5-PPTV-PATCH.1.1
 * CONTRACT:C6-PPTV-RESOLVED.1.1
 * CONTRACT:C8-PPTV-TEXT-FIT.1.1
 */

import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import { builtinModules } from "node:module";
import { relative } from "node:path";
import { fileURLToPath } from "node:url";

import { build, version as esbuildVersion } from "esbuild";

const EXPECTED_ESBUILD_VERSION = "0.28.1";
const packageRoot = fileURLToPath(new URL("../", import.meta.url));
const entry = "src/browser/conformance-entry.ts";
const asset = "assets/pptv-browser-kernel-0.1.iife.js";
const metadataAsset = "assets/pptv-browser-kernel-0.1.meta.json";
const check = process.argv.slice(2).includes("--check");
const unknownArgs = process.argv
  .slice(2)
  .filter((argument) => argument !== "--check");

if (unknownArgs.length > 0) {
  throw new Error(`Unknown browser build arguments: ${unknownArgs.join(" ")}`);
}
if (esbuildVersion !== EXPECTED_ESBUILD_VERSION) {
  throw new Error(
    `Browser kernel requires exact esbuild ${EXPECTED_ESBUILD_VERSION}; loaded ${esbuildVersion}.`,
  );
}

const result = await build({
  absWorkingDir: packageRoot,
  entryPoints: [entry],
  outfile: asset,
  bundle: true,
  platform: "browser",
  format: "iife",
  globalName: "PptvBrowserKernel",
  target: ["es2022"],
  charset: "utf8",
  legalComments: "none",
  minify: false,
  sourcemap: false,
  treeShaking: true,
  metafile: true,
  write: false,
  banner: {
    js: `/*! @office180/pptv browser kernel 0.1 | generated by esbuild ${EXPECTED_ESBUILD_VERSION} */`,
  },
});

const output = result.outputFiles?.find((file) => file.path.endsWith(".js"));
if (output === undefined || result.metafile === undefined) {
  throw new Error("esbuild did not return the expected browser kernel output.");
}

assertPortableMetafile(result.metafile);
const outputBytes = Buffer.from(output.contents);
const sha256 = createHash("sha256").update(outputBytes).digest("hex");
const inputPaths = Object.keys(result.metafile.inputs).sort();
const metadataBytes = Buffer.from(
  `${JSON.stringify(
    {
      schema: "pptv-browser-kernel-build/0.1",
      generator: {
        name: "esbuild",
        version: EXPECTED_ESBUILD_VERSION,
      },
      entry,
      output: asset,
      globalName: "PptvBrowserKernel",
      target: "es2022",
      sha256,
      bytes: outputBytes.byteLength,
      inputs: inputPaths,
    },
    null,
    2,
  )}\n`,
);

if (check) {
  await assertExactAsset(asset, outputBytes);
  await assertExactAsset(metadataAsset, metadataBytes);
} else {
  await writeFile(new URL(`../${asset}`, import.meta.url), outputBytes);
  await writeFile(
    new URL(`../${metadataAsset}`, import.meta.url),
    metadataBytes,
  );
  process.stdout.write(
    `built ${asset} (${outputBytes.byteLength} bytes, sha256 ${sha256})\n`,
  );
}

function assertPortableMetafile(metafile) {
  const inputPaths = Object.keys(metafile.inputs);
  const deniedPackages = inputPaths.filter((inputPath) =>
    /(?:^|[/\\])(?:fontkit|jszip)(?:@|[/\\])/iu.test(inputPath),
  );
  if (deniedPackages.length > 0) {
    throw new Error(
      `Browser kernel reached denied packages:\n${deniedPackages.join("\n")}`,
    );
  }

  const builtinNames = new Set(
    builtinModules.flatMap((name) => [
      name,
      name.startsWith("node:") ? name.slice(5) : `node:${name}`,
    ]),
  );
  const deniedImports = [];
  for (const [inputPath, input] of Object.entries(metafile.inputs)) {
    for (const imported of input.imports) {
      if (
        builtinNames.has(imported.path) ||
        /(?:^|[/\\])(?:fontkit|jszip)(?:@|[/\\])/iu.test(imported.path)
      ) {
        deniedImports.push(`${inputPath} -> ${imported.path}`);
      }
    }
  }
  if (deniedImports.length > 0) {
    throw new Error(
      `Browser kernel reached denied imports:\n${deniedImports.join("\n")}`,
    );
  }

  const requiredSharedInputs = [
    "src/core/scan.ts",
    "src/core/deck.ts",
    "src/core/resolved.ts",
    "src/ops/patch.ts",
    "src/ops/projections.ts",
    "src/browser/session.ts",
  ];
  for (const required of requiredSharedInputs) {
    if (
      !inputPaths.some((inputPath) => normalized(inputPath).endsWith(required))
    ) {
      throw new Error(
        `Browser kernel is missing shared TypeScript input "${required}".`,
      );
    }
  }

  if (
    !inputPaths.some((inputPath) =>
      normalized(inputPath).endsWith("node_modules/saxes/saxes.js"),
    )
  ) {
    throw new Error(
      'Browser kernel is missing the required browser-safe "saxes" XML parser.',
    );
  }
}

async function assertExactAsset(relativePath, expected) {
  const absoluteUrl = new URL(`../${relativePath}`, import.meta.url);
  let actual;
  try {
    actual = await readFile(absoluteUrl);
  } catch {
    throw new Error(
      `Missing generated browser artifact ${relativePath}; run pnpm browser:build.`,
    );
  }
  if (!actual.equals(expected)) {
    const displayPath = relative(packageRoot, fileURLToPath(absoluteUrl));
    throw new Error(
      `Generated browser artifact ${displayPath} is stale; run pnpm browser:build.`,
    );
  }
}

function normalized(path) {
  return path.replaceAll("\\", "/");
}
