/**
 * Build/check the deterministic writable editor IIFE.
 *
 * CONTRACT:C4-PPTV-SOURCE.2.0
 * CONTRACT:C5-PPTV-PATCH.2.0
 * CONTRACT:C6-PPTV-RESOLVED.2.0
 * CONTRACT:C8-PPTV-TEXT-FIT.2.0
 */

import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import { builtinModules } from "node:module";
import { relative } from "node:path";
import { fileURLToPath } from "node:url";

import { build, version as esbuildVersion } from "esbuild";

const EXPECTED_ESBUILD_VERSION = "0.28.1";
const packageRoot = fileURLToPath(new URL("../", import.meta.url));
const entry = "src/browser/editor-app.ts";
const asset = "assets/vector180-editor-0.1.app.js";
const check = process.argv.slice(2).includes("--check");
const unknownArguments = process.argv
  .slice(2)
  .filter((argument) => argument !== "--check");

if (unknownArguments.length > 0) {
  throw new Error(
    `Unknown editor build arguments: ${unknownArguments.join(" ")}`,
  );
}
if (esbuildVersion !== EXPECTED_ESBUILD_VERSION) {
  throw new Error(
    `Vector180 editor requires exact esbuild ${EXPECTED_ESBUILD_VERSION}; loaded ${esbuildVersion}.`,
  );
}

const result = await build({
  absWorkingDir: packageRoot,
  entryPoints: [entry],
  outfile: asset,
  bundle: true,
  platform: "browser",
  format: "iife",
  target: ["es2022"],
  charset: "utf8",
  legalComments: "none",
  minify: false,
  sourcemap: false,
  treeShaking: true,
  metafile: true,
  write: false,
  banner: {
    js: `/*! @office180/vector180 writable editor 0.1 | generated by esbuild ${EXPECTED_ESBUILD_VERSION} */`,
  },
});

const output = result.outputFiles?.find((file) => file.path.endsWith(".js"));
if (output === undefined || result.metafile === undefined) {
  throw new Error("esbuild did not return the expected editor output.");
}
assertPortableMetafile(result.metafile);

const outputBytes = Buffer.from(output.contents);
const sha256 = createHash("sha256").update(outputBytes).digest("hex");
if (check) {
  await assertExactAsset(asset, outputBytes);
} else {
  await writeFile(new URL(`../${asset}`, import.meta.url), outputBytes);
  process.stdout.write(
    `built ${asset} (${outputBytes.byteLength} bytes, sha256 ${sha256})\n`,
  );
}

function assertPortableMetafile(metafile) {
  const inputPaths = Object.keys(metafile.inputs);
  const deniedPackages = inputPaths.filter((inputPath) =>
    /(?:^|[/\\])(?:fontkit|jszip)(?:@|[/\\])/iu.test(inputPath),
  );
  if (deniedPackages.length > 0) {
    throw new Error(
      `Writable editor reached denied packages:\n${deniedPackages.join("\n")}`,
    );
  }

  const builtinNames = new Set(
    builtinModules.flatMap((name) => [
      name,
      name.startsWith("node:") ? name.slice(5) : `node:${name}`,
    ]),
  );
  const deniedImports = [];
  for (const [inputPath, input] of Object.entries(metafile.inputs)) {
    for (const imported of input.imports) {
      if (
        builtinNames.has(imported.path) ||
        /(?:^|[/\\])(?:fontkit|jszip)(?:@|[/\\])/iu.test(imported.path)
      ) {
        deniedImports.push(`${inputPath} -> ${imported.path}`);
      }
    }
  }
  if (deniedImports.length > 0) {
    throw new Error(
      `Writable editor reached denied imports:\n${deniedImports.join("\n")}`,
    );
  }

  const requiredSharedInputs = [
    "src/browser/editor-app.ts",
    "src/browser/session.ts",
    "src/browser/text-measurer.ts",
    "src/core/deck.ts",
    "src/core/resolved.ts",
    "src/core/text-fit.ts",
    "src/core/extract.ts",
    "src/ops/patch.ts",
    "src/ops/projections.ts",
  ];
  for (const required of requiredSharedInputs) {
    if (
      !inputPaths.some((inputPath) => normalized(inputPath).endsWith(required))
    ) {
      throw new Error(
        `Writable editor is missing shared TypeScript input "${required}".`,
      );
    }
  }
}

async function assertExactAsset(relativePath, expected) {
  const absoluteUrl = new URL(`../${relativePath}`, import.meta.url);
  let actual;
  try {
    actual = await readFile(absoluteUrl);
  } catch {
    throw new Error(
      `Missing generated editor artifact ${relativePath}; run node scripts/build-editor-app.mjs.`,
    );
  }
  if (!actual.equals(expected)) {
    const displayPath = relative(packageRoot, fileURLToPath(absoluteUrl));
    throw new Error(
      `Generated editor artifact ${displayPath} is stale; run node scripts/build-editor-app.mjs.`,
    );
  }
}

function normalized(path) {
  return path.replaceAll("\\", "/");
}
